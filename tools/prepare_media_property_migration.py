#!/usr/bin/env python3

import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile


PROFILES = {
    "camera-dump": (b"cam.dipsavefile.enable\0", b"vendor.cam.dipsavefile\0"),
    "omx-core": (b"mtk.vendor.omx.core.log\0", b"vendor.mtk.omx.core_log\0"),
}
INPUTS = {
    "e05e576c4dac9bdff507e1904814a9df104f723c7e6b582392d3ff3b13ad300c": {
        "profile": "camera-dump", "architecture": "arm64", "elf_class": 2,
        "machine": 183, "offset": 0x16801, "filename": "libcam.iopipe.so",
    },
    "48f37a722850e21386b8c4eec02f3266c2306106350eb7b537b96f986dabdee0": {
        "profile": "omx-core", "architecture": "arm", "elf_class": 1,
        "machine": 40, "offset": 0x1F4C, "filename": "libMtkOmxCore.so",
    },
    "36f0baab53a4d3b658acecf9b93023c3d07d7a04c3e566722133b909961a35c5": {
        "profile": "omx-core", "architecture": "arm64", "elf_class": 2,
        "machine": 183, "offset": 0x1A55, "filename": "libMtkOmxCore.so",
    },
}


def prepare(data, profile, architecture):
    digest = hashlib.sha256(data).hexdigest()
    identity = INPUTS.get(digest)
    if identity is None:
        raise ValueError("Unsupported input SHA256; refusing an unreviewed blob.")
    if identity["profile"] != profile or identity["architecture"] != architecture:
        raise ValueError("Profile or architecture does not match the pinned input.")
    if (data[:4] != b"\x7fELF" or data[4] != identity["elf_class"] or data[5] != 1
            or int.from_bytes(data[18:20], "little") != identity["machine"]):
        raise ValueError("ELF architecture does not match the pinned input.")
    old_name, new_name = PROFILES[profile]
    offset = identity["offset"]
    if len(old_name) != len(new_name):
        raise ValueError("The migration must preserve the literal byte length.")
    if data.count(old_name) != 1 or data[offset:offset + len(old_name)] != old_name:
        raise ValueError("The reviewed literal moved or is not unique.")
    if new_name in data:
        raise ValueError("The new literal already exists in the input.")
    migrated = data[:offset] + new_name + data[offset + len(old_name):]
    evidence = dict(identity, input_sha256=digest,
                    output_sha256=hashlib.sha256(migrated).hexdigest(),
                    literal_size=len(old_name), old_property=old_name[:-1].decode(),
                    new_property=new_name[:-1].decode(), installed=False,
                    scope="Generated bytes only; never installs or flashes.")
    return migrated, evidence


def write_candidate(input_path, output_path, data, identity, generated_root=None):
    if input_path.resolve() == output_path.resolve():
        raise ValueError("Refusing to overwrite the input.")
    if output_path.exists() and input_path.samefile(output_path):
        raise ValueError("Refusing a hard link to the input.")
    if generated_root is None:
        with output_path.open("xb") as destination:
            destination.write(data)
        return
    root = generated_root.resolve()
    if root.parent.name != "lenovo-media-property-migration":
        raise ValueError("Replacement requires the dedicated build-output root.")
    if any(os.path.lexists(parent / ".git") for parent in (root, *root.parents)):
        raise ValueError("Generated replacement inside a source repository is forbidden.")
    expected = root / identity["profile"] / identity["architecture"] / identity["filename"]
    if output_path.resolve() != expected:
        raise ValueError("Output is not the exact profile/architecture build path.")
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(dir=output_path.parent, prefix=output_path.name + ".", delete=False) as destination:
            temporary_path = Path(destination.name)
            destination.write(data)
            destination.flush()
            os.fchmod(destination.fileno(), 0o644)
        os.replace(temporary_path, output_path)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()


def main():
    parser = argparse.ArgumentParser(description="Prepare pinned camera/OMX property literals; never installs.")
    parser.add_argument("input", type=Path)
    parser.add_argument("--profile", choices=sorted(PROFILES), required=True)
    parser.add_argument("--architecture", choices=["arm", "arm64"], required=True)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--replace-generated", action="store_true")
    parser.add_argument("--generated-root", type=Path)
    args = parser.parse_args()
    if args.replace_generated and (args.output is None or args.generated_root is None):
        parser.error("--replace-generated requires --output and --generated-root")
    if args.generated_root is not None and not args.replace_generated:
        parser.error("--generated-root requires --replace-generated")
    try:
        migrated, evidence = prepare(args.input.read_bytes(), args.profile, args.architecture)
        if args.output is not None:
            write_candidate(args.input, args.output, migrated, evidence,
                            args.generated_root if args.replace_generated else None)
            evidence["candidate_file"] = str(args.output)
    except (OSError, ValueError) as error:
        print("Error:", error, file=sys.stderr)
        return 2
    print(json.dumps(evidence, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
