#!/usr/bin/env python3
"""Retire the absent emdlogger1 dispatcher selection in one pinned executable."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import sys
import tempfile


INPUT_SHA256 = "98d7ab98c4abf5139d01b84ac9eb4dc9bcec275789857e77087f5b486589cf19"
INPUT_SIZE = 91636
OUTPUT_SHA256 = "1a81767ca29c669884df518a2a2702c14bc251046ceeff2edc48d768e41b7ae8"


# File offsets equal virtual addresses in the pinned RX LOAD. The legacy
# initializer needs twelve bytes rather than eight. Its adjacent four-byte
# stack-canary GOT displacement moves from fce0 to the now unused emdlogger1
# literal fd94; only its single LDR at f9b0 changes. PC-add at f9b4 is unchanged.
# Both inline sequences retain their own original function/frame and never call.
PATCHES = (
    (0xF5BC, bytes.fromhex("5a482021202223467844009058487844fdf77ef9"),
     bytes.fromhex("46f6903078440221017003e000bf00bf00bf00bf"),
     "modern emdlogger1: inline unsupported=2; branch to f5d0"),
    (0xF9B0, bytes.fromhex("cb48"), bytes.fromhex("f848"),
     "same stack-canary GOT displacement, relocated from fce0 to fd94"),
    (0xFCD8, bytes.fromhex("2e4878445ee000bf14580000"),
     bytes.fromhex("46f2f45078440221017064e0"),
     "legacy emdlogger1: inline unsupported=2; branch to fdae"),
    (0xFD94, bytes.fromhex("b329ffff"), bytes.fromhex("14580000"),
     "unused emdlogger1 literal now holds original fce0 canary displacement"),
)


def prepare(data):
    digest = hashlib.sha256(data).hexdigest()
    if digest != INPUT_SHA256 or len(data) != INPUT_SIZE:
        raise ValueError("Unsupported input SHA256 or allocation length; refusing an unreviewed blob.")
    if data[:6] != b"\x7fELF\x01\x01" or struct.unpack_from("<H", data, 18)[0] != 40:
        raise ValueError("Expected the pinned little-endian ARM32 ELF.")
    candidate = bytearray(data)
    reviewed_offsets = set()
    ranges = []
    for offset, old, new, purpose in PATCHES:
        if len(old) != len(new) or data[offset:offset + len(old)] != old:
            raise ValueError("Reviewed instruction allocation or exact bytes changed.")
        candidate[offset:offset + len(old)] = new
        reviewed_offsets.update(range(offset, offset + len(old)))
        ranges.append(dict(offset=offset, size=len(old), old_hex=old.hex(), new_hex=new.hex(), purpose=purpose))
    changed = [i for i, (old, new) in enumerate(zip(data, candidate)) if old != new]
    if len(candidate) != len(data) or not changed or not set(changed) <= reviewed_offsets:
        raise ValueError("Unexpected changed range or allocation length.")
    migrated = bytes(candidate)
    if hashlib.sha256(migrated).hexdigest() != OUTPUT_SHA256:
        raise ValueError("Generated output does not match the reviewed output SHA256.")
    return migrated, dict(input_sha256=digest, output_sha256=hashlib.sha256(migrated).hexdigest(),
                          allocation_length=len(migrated), patches=ranges, changed_offsets=changed,
                          unsupported_state=2, installed=False,
                          scope="Generated bytes only; emdlogger1 dispatch selection; never installs or flashes.")


SOURCE_TOOL = Path("device/lenovo/mt6765-common/tools/prepare_modem_logger_migration.py")


def workspace_out():
    """Locate the checkout from a real source file or the installed launcher.

    Embedded Python's __file__ can be a fictitious member inside the launcher
    zip. Only an existing source file at the exact checkout-relative location
    anchors source execution. Packaged execution uses sys.argv[0], walking to
    the checkout that owns its out/ directory; it never appends out to out.
    """
    module = Path(__file__).resolve()
    if module.is_file() and module.as_posix().endswith("/" + SOURCE_TOOL.as_posix()):
        return module.parents[4] / "out"
    launcher = Path(sys.argv[0]).resolve(strict=True)
    for parent in launcher.parents:
        if parent.name == "out":
            checkout = parent.parent
            if (checkout / SOURCE_TOOL).is_file() and (checkout / ".repo").is_dir():
                return parent
    raise ValueError("Cannot locate the installed launcher's workspace out tree.")


def write_candidate(input_path, output_path, data, generated_root=None):
    if input_path.resolve() == output_path.resolve():
        raise ValueError("Refusing to overwrite the input.")
    if output_path.exists() and input_path.samefile(output_path):
        raise ValueError("Refusing a hard link to the input.")
    if generated_root is None:
        with output_path.open("xb") as destination:
            destination.write(data)
        return
    root = generated_root.absolute()
    output = output_path.absolute()
    # Reject aliases before resolving: includes dangling symlinks and symlinked
    # ancestors, even if their target happens to remain inside out/.
    if any(parent.is_symlink() for parent in (output, *output.parents, root, *root.parents)):
        raise ValueError("Generated paths must not contain symbolic links.")
    root = root.resolve()
    if not root.is_relative_to(workspace_out().resolve()):
        raise ValueError("Generated replacement must remain inside this workspace's out tree.")
    if root.parent.name != "lenovo-modem-logger-migration":
        raise ValueError("Replacement requires the dedicated build-output root.")
    if any(os.path.lexists(parent / ".git") for parent in (root, *root.parents)):
        raise ValueError("Generated replacement inside a source repository is forbidden.")
    if output != root / "ccci_mdinit":
        raise ValueError("Output is not the exact generated executable path.")
    if output.exists() and output.stat().st_nlink != 1:
        raise ValueError("Generated output must not have hard-link aliases.")
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(dir=output.parent, prefix="ccci_mdinit.", delete=False) as destination:
            temporary_path = Path(destination.name)
            destination.write(data)
            destination.flush()
            os.fchmod(destination.fileno(), 0o755)
        os.replace(temporary_path, output)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--replace-generated", action="store_true")
    parser.add_argument("--generated-root", type=Path)
    args = parser.parse_args()
    if args.replace_generated and (args.output is None or args.generated_root is None):
        parser.error("--replace-generated requires --output and --generated-root")
    if args.generated_root is not None and not args.replace_generated:
        parser.error("--generated-root requires --replace-generated")
    try:
        migrated, evidence = prepare(args.input.read_bytes())
        if args.output is not None:
            write_candidate(args.input, args.output, migrated, args.generated_root if args.replace_generated else None)
            evidence["candidate_file"] = str(args.output)
    except (OSError, ValueError) as error:
        print("Error:", error, file=sys.stderr)
        return 2
    print(json.dumps(evidence, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
